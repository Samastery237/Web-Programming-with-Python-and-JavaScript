names = ["Harry", "Ron", "Hermione", "Ginny"]

# First: Defining a list of names

print(names)  # ['Harry', 'Ron', 'Hermione', 'Ginny']
print(names[0])  # Harry

#Second: Using the append method to add an element to the end of the list and using the sort method to sort the list in alphabetical order
names.append("Draco")
names.sort()
print(names)  # ['Draco', 'Ginny', 'Hermione', 'Ron', 'Harry']

